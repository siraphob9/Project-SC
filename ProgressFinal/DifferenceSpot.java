public class DifferenceSpot { // สร้างคลาส DifferenceSpot ใช้สำหรับเก็บข้อมูล "จุดที่ต่างกัน" (จุดจับผิดภาพ) แต่ละจุดบนหน้าจอ
    private int x; // พิกัดแกน X (แนวนอน) ของจุดศูนย์กลางที่จับผิดภาพ
    private int y; // พิกัดแกน Y (แนวตั้ง) ของจุดศูนย์กลางที่จับผิดภาพ
    private int radius; // รัศมีของวงกลม (กำหนดว่าผู้เล่นสามารถคลิกคลาดเคลื่อนได้กว้างแค่ไหนถึงจะยังถือว่าโดนจุดนี้)
    private boolean found; // สถานะเก็บว่าผู้เล่นหาจุดนี้เจอหรือยัง (true = เจอแล้ว, false = ยังไม่เจอ)

    public DifferenceSpot(int x, int y, int radius) { // Constructor ทำงานตอนที่มีการสร้างจุดจับผิดภาพจุดใหม่ขึ้นมา
        this.x = x; // เอาค่าพิกัด X ที่ตั้งไว้ มาใส่ในตัวแปร x ของคลาสนี้
        this.y = y; // เอาค่าพิกัด Y ที่ตั้งไว้ มาใส่ในตัวแปร y
        this.radius = radius; // เอาค่าขนาดความกว้างรัศมี มาใส่ในตัวแปร radius
        this.found = false; // ค่าเริ่มต้นกำหนดให้ "ยังหาไม่เจอ" (false) ไว้ก่อนเสมอ
    }

    /** TODO: เช็คว่าพิกัดคลิกอยู่ในวงกลมของจุดนี้หรือไม่ */ // คอมเมนต์ดั้งเดิมที่เขียนโน้ตไว้ในโค้ด
    public boolean contains(int clickX, int clickY) { // ฟังก์ชันสำคัญ เอาไว้คำนวณว่าพิกัดที่เมาส์คลิก โดนพื้นที่จุดจับผิดนี้ไหม
        long dx = clickX - x; // หาระยะห่างในแนวนอน ระหว่างตำแหน่งที่คลิก กับจุดศูนย์กลางของจุดจับผิด
        long dy = clickY - y; // หาระยะห่างในแนวตั้ง ระหว่างตำแหน่งที่คลิก กับจุดศูนย์กลางของจุดจับผิด
        // ใช้หลักการคณิตศาสตร์ (ทฤษฎีบทพีทาโกรัส) โดยเอา (ระยะห่าง X ยกกำลังสอง) + (ระยะห่าง Y ยกกำลังสอง) 
        // แล้วเทียบว่ามันน้อยกว่าหรือเท่ากับ (รัศมียกกำลังสอง) หรือไม่ ถ้าใช่แปลว่าคลิกอยู่ในวงกลมพอดี คืนค่าเป็นจริง (true)
        return dx * dx + dy * dy <= (long) radius * radius;
    }

    public int getX() { return x; } // ฟังก์ชันส่งออกค่าพิกัด X ไปให้คลาสอื่นใช้งาน
    public int getY() { return y; } // ฟังก์ชันส่งออกค่าพิกัด Y ไปให้คลาสอื่นใช้งาน
    public int getRadius() { return radius; } // ฟังก์ชันส่งออกค่ารัศมีวงกลม
    public boolean isFound() { return found; } // ฟังก์ชันส่งออกสถานะว่า จุดนี้ถูกหาเจอไปหรือยัง
    public void setFound(boolean found) { this.found = found; } // ฟังก์ชันสำหรับสั่งเปลี่ยนสถานะจุดนี้ (เช่น สั่งเป็น true เมื่อผู้เล่นคลิกเจอแล้ว)
}